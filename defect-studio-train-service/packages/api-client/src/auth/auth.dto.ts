// Request and response shapes for /api/auth/* on the BFF.
// Dates arrive as ISO strings; UUIDs as strings.

export interface User {
  id: string;
  email: string;
  name: string | null;
  role: string;
  created_at: string;
}

export interface TokenResponse {
  access_token: string;
  refresh_token: string;
  token_type: string;
  user: User;
}

export interface LoginRequest {
  email: string;
  password: string;
}

